channel_data = importdata(fullfile(dir_of_poster_data,"c1_raw.mat"));

[peaks,peak_locs]= findpeaks(channel_data * -1);
[valleys,valley_locs]= findpeaks(channel_data);

diff_between_peaks_and_vals = peaks - valleys;
[~,best_rep]= max(diff_between_peaks_and_vals);
[~,worst_rep] = min(diff_between_peaks_and_vals);

best_peak_idx = peak_locs(best_rep);
best_valley_idx = valley_locs(best_rep);
plotting_range = best_peak_idx - 29:1:best_peak_idx+30;
plotting_data = channel_data(plotting_range)*-1;
figure;
plot(plotting_data,"DisplayName","Waveform");hold on;
scatter(30,plotting_data(30),100,"yellow","filled",'DisplayName',"Peak");
scatter(54,plotting_data(54),100,"magenta" ,"filled",'DisplayName',"Valley");
legend();
title("Has Valley")

