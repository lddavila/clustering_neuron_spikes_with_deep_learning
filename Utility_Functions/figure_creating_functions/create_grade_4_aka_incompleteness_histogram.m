close all;clc;

[config,local_figure_dir] = set_up_figure_creation("name_of_calling_file","create_grade_4_aka_incompleteness_histogram");
dir_of_poster_data = fullfile(config.data_dir,"data_for_poster_figs");
aligned = importdata(fullfile(dir_of_poster_data,"t1 aligned_to_peak_wf.mat"));
the_waveform_peaks = get_peaks(aligned,true);
% Combine the supplied peak values into one vector.


% Required variables:
%   the_waveform_peaks : spike peak values
%   the_channel_tval  : detection threshold for each channel

channel_index = 1;  % Change to 2 to plot the second channel.

thresholds = the_channel_tval(:);
num_channels = numel(thresholds);

validateattributes(channel_index, {'numeric'}, ...
    {'scalar','integer','>=',1,'<=',num_channels});

threshold = thresholds(channel_index);
validateattributes(threshold, {'numeric'}, {'scalar','real','finite'});

% Select peaks for the chosen channel.
if isvector(the_waveform_peaks)
    % Assumes this vector already belongs to channel_index.
    peaks = the_waveform_peaks(:);

elseif size(the_waveform_peaks, 2) == num_channels
    % Spikes × channels.
    peaks = the_waveform_peaks(:, channel_index);

elseif size(the_waveform_peaks, 1) == num_channels
    % Channels × spikes.
    peaks = the_waveform_peaks(channel_index, :).';

else
    error(['Cannot identify the channel dimension. Supply peaks as ' ...
           'spikes-by-channels or channels-by-spikes.']);
end

peaks = double(peaks);
peaks = peaks(isfinite(peaks));

if isempty(peaks)
    error('The selected channel has no finite peak values.');
end

% Compute histogram and locate its mode.
[n, xout] = hist(peaks, 21);
n = n(:).';
xout = xout(:).';

[~, mode_idx] = max(n);
mode_amplitude = xout(mode_idx);
delta = xout(2) - xout(1);

% Reconstruct a symmetric distribution using the right-side counts.
right_centers = xout(mode_idx + 1:end);
right_counts  = n(mode_idx + 1:end);

left_centers = 2 * mode_amplitude - fliplr(right_centers);

theo_vals = [left_centers, mode_amplitude, right_centers];
theo_n   = [fliplr(right_counts), n(mode_idx), right_counts];

below_threshold = theo_vals < threshold;
incompleteness = sum(theo_n(below_threshold)) / sum(theo_n);

% Colors.
blue   = [0.25 0.55 0.78];
orange = [0.90 0.40 0.15];
gray   = [0.25 0.25 0.25];

% Create plot.
f = figure('Color', 'w', 'Units', 'inches', ...
    'Position', [1 1 10 8]);

ax = axes(f);
hold(ax, 'on');

% Reconstructed histogram with below-threshold bins highlighted.
b = bar(ax, theo_vals, theo_n, 1, ...
    'FaceColor', 'flat', ...
    'EdgeColor', 'w', ...
    'LineWidth', 0.75, ...
    'HandleVisibility', 'off');

bar_colors = repmat(blue, numel(theo_n), 1);
bar_colors(below_threshold, :) = ...
    repmat(orange, nnz(below_threshold), 1);
b.CData = bar_colors;

% Outline of the observed histogram.
edges = [xout - delta/2, xout(end) + delta/2];

h_observed = stairs(ax, ...
    [edges(1), edges], [0, n, 0], ...
    'Color', gray, ...
    'LineWidth', 2.2);

% Legend entries for reconstructed counts.
h_reconstructed = patch(ax, NaN, NaN, blue, ...
    'EdgeColor', 'none');

h_missing = patch(ax, NaN, NaN, orange, ...
    'EdgeColor', 'none');

% Mode and threshold markers.
xline(ax, mode_amplitude, ':', 'Mode', ...
    'Color', gray, ...
    'LineWidth', 1.5, ...
    'FontSize', 14, ...
    'LabelVerticalAlignment', 'middle', ...
    'HandleVisibility', 'off');

xline(ax, threshold, '--', 'Detection threshold', ...
    'Color', orange, ...
    'LineWidth', 2, ...
    'FontSize', 14, ...
    'LabelVerticalAlignment', 'middle', ...
    'HandleVisibility', 'off');

% Arrow indicating reflection from right to left.
peak_count = max([n, theo_n]);
reflection_span = xout(end) - mode_amplitude;

if reflection_span > 0
    arrow_start = mode_amplitude + 0.75 * reflection_span;
    arrow_end   = mode_amplitude - 0.75 * reflection_span;

    quiver(ax, arrow_start, 1.12 * peak_count, ...
        arrow_end - arrow_start, 0, 0, ...
        'Color', blue, ...
        'LineWidth', 2, ...
        'MaxHeadSize', 0.15, ...
        'HandleVisibility', 'off');

    text(ax, mode_amplitude, 1.19 * peak_count, ...
        'Mirror right-side counts about the mode', ...
        'HorizontalAlignment', 'center', ...
        'FontSize', 14, ...
        'Color', blue);
end

% Labels and layout.
all_x = [xout, theo_vals, threshold];
xlim(ax, [min(all_x) - delta, max(all_x) + delta]);
ylim(ax, [0, 1.35 * peak_count]);

xlabel(ax, 'Spike peak amplitude (\muV)');
ylabel(ax, 'Spike count');
title(ax, sprintf('Estimated incompleteness: %.1f%%', ...
    100 * incompleteness));

legend(ax, [h_observed, h_reconstructed, h_missing], ...
    {'Observed counts', ...
     'Reconstructed counts', ...
     'Estimated undetected counts'}, ...
    'Location', 'southoutside', ...
    'Box', 'off');

set(ax, ...
    'FontName', 'Arial', ...
    'FontSize', 16, ...
    'LineWidth', 1.2, ...
    'Box', 'off', ...
    'TickDir', 'out');

hold(ax, 'off');
